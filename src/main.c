#include "analyzer.h"
#include "ast.h"
#include "bytecode.h"
#include "common.h"
#include "parser.h"
#include "scanner.h"
#include "symbol_table.h"
#include "vm.h"

static void print_usage(const char *prog) {
    printf("PyC Compiler & Virtual Machine\n\n");
    printf("Usage: %s [options] <source-file>\n\n", prog);
    printf("Options:\n");
    printf("  --tokens     Print lexical token stream\n");
    printf("  --ast        Print Abstract Syntax Tree\n");
    printf("  --symtab     Print scoped symbol table\n");
    printf("  --bytecode   Disassemble generated bytecode\n");
    printf("  --trace      Trace VM instruction execution\n");
    printf("  --check      Run frontend (lex + parse + semantic check) only\n");
    printf("  -h, --help   Show this help message\n");
}

int main(int argc, char *argv[]) {
    bool dump_tokens = false;
    bool dump_ast = false;
    bool dump_symtab = false;
    bool dump_bytecode = false;
    bool trace_vm = false;
    bool check_only = false;
    const char *file_path = NULL;

    for (int i = 1; i < argc; ++i) {
        if (strcmp(argv[i], "--tokens") == 0) {
            dump_tokens = true;
        } else if (strcmp(argv[i], "--ast") == 0) {
            dump_ast = true;
        } else if (strcmp(argv[i], "--symtab") == 0) {
            dump_symtab = true;
        } else if (strcmp(argv[i], "--bytecode") == 0) {
            dump_bytecode = true;
        } else if (strcmp(argv[i], "--trace") == 0) {
            trace_vm = true;
        } else if (strcmp(argv[i], "--check") == 0) {
            check_only = true;
        } else if (strcmp(argv[i], "-h") == 0 || strcmp(argv[i], "--help") == 0) {
            print_usage(argv[0]);
            return 0;
        } else if (argv[i][0] == '-') {
            fprintf(stderr, "Unknown option: %s\n", argv[i]);
            print_usage(argv[0]);
            return 1;
        } else {
            file_path = argv[i];
        }
    }

    if (!file_path) {
        print_usage(argv[0]);
        return 1;
    }

    char *source = pyc_read_file(file_path, NULL);
    if (!source) {
        fprintf(stderr, "Error: cannot open source file '%s'\n", file_path);
        return 1;
    }

    int exit_code = 0;
    DiagnosticList diags;
    diag_init(&diags);

    TokenList tokens;
    token_list_init(&tokens);

    TreeNode *ast = NULL;
    Analyzer *analyzer = NULL;
    BytecodeProgram *bytecode = NULL;

    /* Stage 1: Lexing */
    if (!scan_source(source, &tokens, &diags)) {
        diag_print(&diags, "Lexical", stderr);
        exit_code = 1;
        goto cleanup;
    }
    if (dump_tokens) {
        printf("=== Tokens ===\n");
        print_tokens(&tokens, stdout);
        printf("\n");
    }

    /* Stage 2: Parsing */
    ast = parse_tokens(&tokens, &diags);
    if (diags.count > 0) {
        diag_print(&diags, "Syntax", stderr);
        exit_code = 1;
        goto cleanup;
    }

    /* Stage 3: Semantic Analysis & Symbol Table */
    analyzer = analyzer_create(ast, &diags);
    if (!analyzer_run(analyzer)) {
        if (dump_ast) {
            printf("=== Abstract Syntax Tree ===\n");
            ast_print(ast, stdout);
            printf("\n");
        }
        diag_print(&diags, "Semantic", stderr);
        exit_code = 1;
        goto cleanup;
    }

    if (dump_ast) {
        printf("=== Abstract Syntax Tree ===\n");
        ast_print(ast, stdout);
        printf("\n");
    }
    if (dump_symtab) {
        printf("=== Symbol Table ===\n");
        st_print(analyzer_get_symbol_table(analyzer), stdout);
        printf("\n");
    }

    if (check_only && !dump_bytecode) {
        printf("Check passed: %s\n", file_path);
        goto cleanup;
    }

    /* Stage 4: Bytecode Compilation */
    bytecode = bytecode_compile(ast, analyzer_get_symbol_table(analyzer), &diags);
    if (diags.count > 0) {
        diag_print(&diags, "Codegen", stderr);
        exit_code = 1;
        goto cleanup;
    }
    if (dump_bytecode) {
        bytecode_disassemble(bytecode, stdout);
        printf("\n");
    }

    if (check_only) {
        printf("Check passed: %s\n", file_path);
        goto cleanup;
    }

    /* Stage 5: Virtual Machine Execution */
    VMConfig cfg;
    cfg.in_stream = stdin;
    cfg.out_stream = stdout;
    cfg.trace_exec = trace_vm;
    cfg.max_steps = 0;

    if (vm_run(bytecode, &cfg, &diags) != VM_OK) {
        diag_print(&diags, "Runtime", stderr);
        exit_code = 1;
        goto cleanup;
    }

cleanup:
    bytecode_free(bytecode);
    analyzer_destroy(analyzer);
    ast_free(ast);
    token_list_free(&tokens);
    diag_free(&diags);
    free(source);
    return exit_code;
}
